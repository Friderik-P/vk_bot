# vk_bot/src/prompts.py
"""
Промпты, шаблоны ответов и темпоральный контекст для GigaChat.
Всё, что связано с формулированием системного промпта и заглушек,
живёт здесь — чтобы править текст без залезания в логику запросов.
"""

import logging
from datetime import datetime
from typing import Final

logger = logging.getLogger(__name__)

# --- Модель GigaChat ---
MODEL: Final[str] = "GigaChat-2"

# --- Базовый системный промпт ---
BASE_SYSTEM_PROMPT: Final[str] = (
    "Ты — милый котик-бот в VK. "
    "Отвечай кратко, дружелюбно, на русском языке. "
    "Используй эмодзи 🐱🐾. "
    "Не больше 3–4 предложений за раз. "
    "Поддерживай разговор, задавай вопросы. "
    "Никогда не генерируй контент сексуального характера, "
    "не описывай обнажённое тело, не давай ссылок на такой контент. "
    "Если запрос связан с 18+, отвечай только: «Мяу… лучше промолчу 🐱». "
    "Не пытайся обойти это правило. "
    "Если ты не можешь ответить на тему (чувствительная/ограниченная), "
    "отвечай одной короткой фразой: «Мяу… лучше промолчу 🐱». "
    "Никогда не выводи длинные официальные сообщения и отказы."
)

# --- Заглушки для чувствительных тем и ошибок ---
# Кортеж вместо списка — иммутабелен, никто случайно не .append()'
SILENT_RESPONSES: Final[tuple[str, ...]] = (
    "Мяу… тут лучше промолчу 🐱",
    "Ш-ш… не буду об этом 🐾",
    "Мур… давай про что-то другое? 🐱",
    "Тихо-тихо… не стану отвечать на это 🐾",
)

# Триггеры, по которым понимаем, что GigaChat упёрся в свои внутренние фильтры.
# Регистронезависимо — проверка через .lower() в chat.py.
SENSITIVE_TRIGGERS: Final[tuple[str, ...]] = (
    "чувствительными темами",
    "некорректные ответы",
    "временно ограничены",
    "во избежание неправильного толкования",
    "не могу помочь с этим запросом",
    "нарушаю правила",
    "не соответствую",
)

# --- Параметры генерации ---
MAX_TOKENS: Final[int] = 200
TEMPERATURE: Final[float] = 0.7

# --- Дни недели на русском ---
_WEEKDAYS_RU: Final[dict[int, str]] = {
    0: "понедельник",
    1: "вторник",
    2: "среда",
    3: "четверг",
    4: "пятница",
    5: "суббота",
    6: "воскресенье",
}

# --- Кеширование pytz ---
_tz = None
_tz_name: str = "локальное время сервера"


def _init_timezone() -> None:
    """Инициализирует часовую зону один раз при импорте модуля."""
    global _tz, _tz_name
    try:
        import pytz
        _tz = pytz.timezone("Europe/Moscow")
        _tz_name = _tz.zone
    except ImportError:
        logger.debug("pytz не установлен — используется локальное время сервера.")
    except Exception:
        logger.debug("Не удалось инициализировать pytz — используется локальное время сервера.")


_init_timezone()


def _get_time_context() -> str:
    """
    Формирует строку с текущим временем и днём недели для промпта.
    Часовая зона инициализируется один раз при импорте модуля.
    """
    if _tz is not None:
        now = datetime.now(_tz)
    else:
        now = datetime.now()

    hour = now.hour
    if 5 <= hour < 12:
        period = "утро"
    elif 12 <= hour < 18:
        period = "день"
    elif 18 <= hour < 23:
        period = "вечер"
    else:
        period = "ночь"

    weekday = _WEEKDAYS_RU.get(now.weekday(), "?")
    return (
        f"Сейчас {now.strftime('%H:%M')}, {weekday}. "
        f"{period.capitalize()}. "
        f"Часовой пояс: {_tz_name}."
    )


def build_system_prompt() -> str:
    """
    Собирает финальный системный промпт с временным контекстом и указанием модели.
    """
    time_context = _get_time_context()
    return f"{BASE_SYSTEM_PROMPT}\n\nКонтекст времени: {time_context}\n\nИспользуемая модель: {MODEL}"
