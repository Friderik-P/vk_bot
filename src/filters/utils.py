# vk_bot/src/filters/utils.py
"""Утилиты для нормализации текста перед фильтрацией."""

import re

# Таблица замен для деобфускации — создаётся один раз при импорте.
# str.translate() — один C-level проход вместо 10 replace().
_DEOBFUSCATE_TABLE = str.maketrans({
    "0": "о",
    "3": "е",
    "4": "а",
    "1": "и",
    "6": "б",
    "@": "а",
    "$": "с",
    "#": "",
    "*": "",
    "|": "",
})

# Модульные regex-паттерны (компилируются один раз)
_NON_WORD = re.compile(r"[^\w\s]|_")
_MULTISPACE = re.compile(r"\s+")

# Таблица транслитерации латиницы → кириллица (для обнаружения смешанных скриптов).
# Закрывает обходы вроде «cекс», «p0rn» → «порн», «s3x» → «сех».
# str.translate() — один C-level проход вместо цикла.
_LATIN_TO_CYRILLIC = str.maketrans({
    "a": "а", "b": "в", "c": "с", "d": "д", "e": "е",
    "f": "ф", "g": "г", "h": "х", "i": "и", "k": "к",
    "l": "л", "m": "м", "n": "н", "o": "о", "p": "п",
    "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "х", "y": "у", "z": "з",
})


def transliterate_to_cyrillic(text: str) -> str:
    """
    Транслитерирует латинские буквы на визуально похожие кириллические.
    Используется фильтром 18+ для перехвата смешанных скриптов
    (латиница + кириллица в одном слове).
    """
    return text.translate(_LATIN_TO_CYRILLIC)


def deobfuscate(text: str) -> str:
    """
    Деобфускация: заменяет популярные подмены символов на буквы.
    Закрывает обходы вроде «с3кс», «п0рно», «4нал», «bl@dь».
    Один проход через str.translate().
    """
    return text.translate(_DEOBFUSCATE_TABLE)


def normalize_text(text: str) -> str:
    """
    Нормализует текст для проверки фильтров:
      - деобфускация (3→е, 0→о и т.д.)
      - нижний регистр
      - ё → е
      - заменяет любые не-буквенно-цифровые символы (включая _) на пробел
      - схлопывает множественные пробелы
      - убирает края
    Возвращает строку из слов, разделённых одним пробелом.
    """
    if not text:
        return ""

    text = deobfuscate(text)
    text = text.lower().replace("ё", "е")
    text = _NON_WORD.sub(" ", text)
    text = _MULTISPACE.sub(" ", text).strip()
    return text
